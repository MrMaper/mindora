// Dedupe by english (case-insensitive), keep first domain
const seen = new Set();
const unique = [];
for (const [domain, en, fa] of rows) {
  const key = en.toLowerCase();
  if (seen.has(key)) continue;
  seen.add(key);
  unique.push({ domain, front: en, back: fa });
}

console.log("unique", unique.length);

const byDomain = {};
for (const row of unique) {
  (byDomain[row.domain] ??= []).push({ front: row.front, back: row.back });
}

