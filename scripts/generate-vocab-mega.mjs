/** @type {Array<[string, string, string]>} domain, english, persian */
const rows = [];

function add(domain, pairs) {
  for (const [en, fa] of pairs) {
    const e = en.trim();
    const f = fa.trim();
    if (!e || !f) continue;
    rows.push([domain, e, f]);
  }
}

